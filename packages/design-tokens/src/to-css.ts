import { font, layout, motion, radius, space } from "./primitives.js";
import { themes, type ColorTheme, type ThemeName } from "./themes.js";

const kebab = (value: string): string => value.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** Flattens a nested token object into `--prefix-key-subkey: value` declarations. */
export function toCustomProperties(tokens: object, prefix: string): string[] {
  return Object.entries(tokens).flatMap(([key, value]) => {
    const name = `${prefix}-${kebab(key)}`;
    return typeof value === "object" && value !== null
      ? toCustomProperties(value, name)
      : [`${name}: ${String(value)};`];
  });
}

const block = (selector: string, declarations: string[]): string =>
  `${selector} {\n${declarations.map((d) => `  ${d}`).join("\n")}\n}`;

const colorDeclarations = (theme: ColorTheme): string[] => [
  ...toCustomProperties(theme, "--color"),
  `color-scheme: ${theme === themes.dark ? "dark" : "light"};`,
];

/**
 * Builds the full stylesheet:
 * - static scales on :root
 * - light theme by default, dark when the OS prefers it (unless a theme is pinned)
 * - every theme addressable via [data-theme="name"]
 */
export function buildCss(): string {
  const scales = [
    ...toCustomProperties(space, "--space"),
    ...toCustomProperties(radius, "--radius"),
    ...toCustomProperties(font, "--font"),
    ...toCustomProperties(motion, "--motion"),
    ...toCustomProperties(layout, "--layout"),
  ];

  const themeBlocks = (Object.keys(themes) as ThemeName[]).map((name) =>
    block(`[data-theme="${name}"]`, colorDeclarations(themes[name])),
  );

  return [
    "/* Generated by @in2eat/design-tokens. Do not edit by hand. */",
    block(":root", [...scales, ...colorDeclarations(themes.light)]),
    `@media (prefers-color-scheme: dark) {\n${block(":root:not([data-theme])", colorDeclarations(themes.dark))}\n}`,
    ...themeBlocks,
    "",
  ].join("\n\n");
}
